def arguments(args: ast.arguments) -> List[ast.arg]:
    found = list(args.posonlyargs) + list(args.args) + list(args.kwonlyargs)
    return found + [arg for arg in (args.vararg, args.kwarg) if arg is not None]


def bound_names(body: Sequence[ast.AST]) -> Set[str]:
    """Names a block binds in its own scope (nested functions, classes and comprehensions excluded)."""
    names: Set[str] = set()
    declared: Set[str] = set()
    pending = list(body)
    while pending:
        node = pending.pop()
        if isinstance(node, FUNCTIONS + (ast.ClassDef,)):
            names.add(node.name)
            continue
        if isinstance(node, ast.Lambda):
            continue
        if isinstance(node, COMPREHENSIONS):
            # Only an assignment expression binds in the enclosing scope.
            for part in ast.walk(node):
                if isinstance(part, ast.NamedExpr) and isinstance(part.target, ast.Name):
                    names.add(part.target.id)
            continue
        if isinstance(node, ast.Name) and not isinstance(node.ctx, ast.Load):
            names.add(node.id)
        elif isinstance(node, ast.ExceptHandler) and node.name:
            names.add(node.name)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            names.update((alias.asname or alias.name).split(".")[0] for alias in node.names)
        elif isinstance(node, (ast.Global, ast.Nonlocal)):
            declared.update(node.names)
        pending.extend(ast.iter_child_nodes(node))
    return names - declared


def global_reads(cls: ast.ClassDef) -> Set[str]:
    """Names the class reads from its module or the builtins, those of string annotations included."""
    reads: Set[str] = set()

    def annotation(node: Optional[ast.AST], scopes: Tuple[Set[str], ...]) -> None:
        if node is None:
            return
        for part in ast.walk(node):
            if isinstance(part, ast.Constant) and isinstance(part.value, str):
                try:
                    parsed = ast.parse(part.value.strip(), mode="eval")
                except SyntaxError:
                    continue
                reads.update(n.id for n in ast.walk(parsed) if isinstance(n, ast.Name))
        visit(node, scopes)

    def visit(node: ast.AST, scopes: Tuple[Set[str], ...]) -> None:
        if isinstance(node, ast.Name):
            if isinstance(node.ctx, ast.Load) and not any(node.id in scope for scope in scopes):
                reads.add(node.id)
            return
        if isinstance(node, FUNCTIONS):
            defaults = node.args.defaults + [default for default in node.args.kw_defaults if default is not None]
            for item in node.decorator_list + defaults:
                visit(item, scopes)
            for arg in arguments(node.args):
                annotation(arg.annotation, scopes)
            annotation(node.returns, scopes)
            inner = scopes + ({arg.arg for arg in arguments(node.args)} | bound_names(node.body),)
            for statement in node.body:
                visit(statement, inner)
            return
        if isinstance(node, ast.Lambda):
            for item in node.args.defaults + [default for default in node.args.kw_defaults if default is not None]:
                visit(item, scopes)
            visit(node.body, scopes + ({arg.arg for arg in arguments(node.args)},))
            return
        if isinstance(node, COMPREHENSIONS):
            generators = node.generators
            visit(generators[0].iter, scopes)
            targets = {n.id for g in generators for n in ast.walk(g.target) if isinstance(n, ast.Name)}
            inner = scopes + (targets,)
            for position, generator in enumerate(generators):
                if position:
                    visit(generator.iter, inner)
                for condition in generator.ifs:
                    visit(condition, inner)
            for part in (node.key, node.value) if isinstance(node, ast.DictComp) else (node.elt,):
                visit(part, inner)
            return
        if isinstance(node, ast.AnnAssign):
            annotation(node.annotation, scopes)
            visit(node.target, scopes)
            if node.value is not None:
                visit(node.value, scopes)
            return
        for child in ast.iter_child_nodes(node):
            visit(child, scopes)

    for item in cls.decorator_list + cls.bases + [keyword.value for keyword in cls.keywords]:
        visit(item, ())
    for statement in cls.body:
        visit(statement, ())
    reads.discard(SYNC_CLASS)  # the class itself, defined by the generated module
    return reads


