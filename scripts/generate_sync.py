class Text:
    """A source text with its lines, to turn (line, column) positions into offsets."""

    def __init__(self, text: str):
        self.text = text
        self.lines = text.split("\n")
        self.starts = [0]
        for line in self.lines:
            self.starts.append(self.starts[-1] + len(line) + 1)

    def offset(self, row: int, col: int) -> int:
        """Offset of a tokenize position (1-based row, column in characters)."""
        return self.starts[row - 1] + col

    def char_col(self, row: int, byte_col: int) -> int:
        """ast columns count UTF-8 bytes: the column in characters."""
        return len(self.lines[row - 1].encode("utf-8")[:byte_col].decode("utf-8"))

    def node_start(self, node: Union[ast.expr, ast.stmt]) -> int:
        return self.offset(node.lineno, self.char_col(node.lineno, node.col_offset))

    def node_end(self, node: Union[ast.expr, ast.stmt]) -> int:
        row = node.end_lineno or node.lineno
        return self.offset(row, self.char_col(row, node.end_col_offset or 0))


def apply_edits(text: str, edits: List[Edit]) -> str:
    out = []
    position = 0
    for start, end, replacement in sorted(edits, key=lambda edit: (edit[0], edit[1])):
        if start < position:
            raise GenerateError(f"two rewrites overlap at offset {start} of the class")
        out.append(text[position:start])
        out.append(replacement)
        position = end
    out.append(text[position:])
    return "".join(out)


def reword(text: str) -> str:
    for old, new in WORDING:
        text = text.replace(old, new)
    return ASYNC_IDENTIFIERS.sub(lambda found: NAMES[found.group(0)], text)


def checked(text: str, where: str) -> str:
    """A docstring or comment of the synchronous class, once reworded: no async wording left."""
    found = ASYNC_WORDS.search(text)
    if found:
        raise GenerateError(
            f"{where}: {found.group(0)!r} left in a docstring or comment: reword client.py or add a WORDING rule"
        )
    return text


def indent_block(block: str, column: int) -> str:
    """A multi-line string literal whose lines after the first are indented to `column`."""
    lines = block.split("\n")
    return "\n".join([lines[0]] + [" " * column + line if line else line for line in lines[1:]])


