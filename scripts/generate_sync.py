def generate(source: str) -> str:
    """The source of leakradar/_sync_client.py for the source of leakradar/client.py."""
    source = source.replace("\r\n", "\n")
    try:
        tree = ast.parse(source)
    except SyntaxError as error:
        raise GenerateError(f"leakradar/client.py does not parse: {error}") from None
    text = Text(source)
    body = rewrite_class(text, find_class(tree))
    imports = import_block(global_reads(parse_class(body, "the rewritten class")), module_bindings(tree, text.lines))
    result = HEADER + "\n" + imports + "\n\n\n" + body.rstrip("\n") + "\n"
    compile(result, "leakradar/_sync_client.py", "exec")
    return result


def _emit(text: str) -> None:
    """Print, even what the console encoding cannot show."""
    encoding = getattr(sys.stdout, "encoding", None) or "utf-8"
    sys.stdout.write(text.encode(encoding, "replace").decode(encoding) + "\n")


def _shown(path: pathlib.Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=str(OUTPUT), help="file to write (default: leakradar/_sync_client.py)")
    parser.add_argument("--check", action="store_true", help="write nothing, exit with 1 when the file is out of date")
    args = parser.parse_args(argv)

    try:
        generated = generate(SOURCE.read_bytes().decode("utf-8"))
    except GenerateError as error:
        _emit(f"error: {error}")
        return 2
    out = pathlib.Path(args.out)
    if args.check:
        # A Windows checkout may have turned the line endings into CRLF.
        current = out.read_bytes().decode("utf-8").replace("\r\n", "\n") if out.exists() else ""
        if current == generated:
            _emit(f"{_shown(out)} is up to date.")
            return 0
        diff = list(difflib.unified_diff(current.splitlines(), generated.splitlines(), _shown(out), "generated", lineterm=""))
        for line in diff[:60]:
            _emit(line)
        if len(diff) > 60:
            _emit(f"... {len(diff) - 60} more lines")
        _emit(f"{_shown(out)} is out of date: run python scripts/generate_sync.py")
        return 1
    out.write_bytes(generated.encode("utf-8"))
    _emit(f"{SYNC_CLASS} written to {_shown(out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
