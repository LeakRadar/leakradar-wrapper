def find_class(tree: ast.Module) -> ast.ClassDef:
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == ASYNC_CLASS:
            return node
    raise GenerateError(f"class {ASYNC_CLASS} not found in leakradar/client.py")


def docstring_node(node: ast.AST) -> Optional[ast.Constant]:
    body = getattr(node, "body", None)
    if isinstance(body, list) and body and isinstance(body[0], ast.Expr):
        value = body[0].value
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            return value
    return None


def awaited_name(node: ast.AST) -> Optional[str]:
    """The name x of `if inspect.isawaitable(x): await x`, else None."""
    if not isinstance(node, ast.If) or node.orelse or len(node.body) != 1:
        return None
    test = node.test
    if not (
        isinstance(test, ast.Call)
        and isinstance(test.func, ast.Attribute)
        and test.func.attr == "isawaitable"
        and isinstance(test.func.value, ast.Name)
        and test.func.value.id == "inspect"
        and len(test.args) == 1
        and not test.keywords
        and isinstance(test.args[0], ast.Name)
    ):
        return None
    statement = node.body[0]
    if not (
        isinstance(statement, ast.Expr)
        and isinstance(statement.value, ast.Await)
        and isinstance(statement.value.value, ast.Name)
        and statement.value.value.id == test.args[0].id
    ):
        return None
    return test.args[0].id


def statement_lists(function: ast.AST) -> List[List[ast.stmt]]:
    """Every list of statements of a function, nested blocks included, nested functions excluded."""
    found: List[List[ast.stmt]] = []
    pending: List[ast.AST] = [function]
    while pending:
        node = pending.pop()
        blocks = [getattr(node, field, None) for field in ("body", "orelse", "finalbody")]
        blocks += [handler.body for handler in getattr(node, "handlers", None) or []]
        for block in blocks:
            if isinstance(block, list) and block and isinstance(block[0], ast.stmt):
                found.append(block)
                pending.extend(s for s in block if not isinstance(s, FUNCTIONS + (ast.ClassDef,)))
    return found


def loads(node: ast.AST, name: str) -> int:
    return sum(1 for n in ast.walk(node) if isinstance(n, ast.Name) and n.id == name and isinstance(n.ctx, ast.Load))


def statement_edits(cls: ast.ClassDef, text: Text) -> Tuple[Set[int], List[Edit]]:
    """Rewrites decided on the syntax tree: _READ_ENV and the awaitable checks. Returns the rows
    they own (the token pass leaves them alone) and the edits."""
    rows: Set[int] = set()
    edits: List[Edit] = []

    # _READ_ENV = False -> True, under a comment of its own.
    read_env: Optional[ast.stmt] = None
    for node in cls.body:
        targets = node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
        if any(isinstance(target, ast.Name) and target.id == "_READ_ENV" for target in targets):
            read_env = node
    value = getattr(read_env, "value", None)
    if read_env is None or value is None:
        raise GenerateError(f"{ASYNC_CLASS} has no `_READ_ENV = ...` class attribute")
    edits.append((text.node_start(value), text.node_end(value), "True"))
    row = read_env.lineno
    line = text.lines[row - 1]
    indent = line[: len(line) - len(line.lstrip())]
    first = row
    while first > 1 and text.lines[first - 2].strip().startswith("#"):
        first -= 1
    rows.update(range(first, row))
    edits.append((text.starts[first - 1], text.starts[row - 1], indent + READ_ENV_COMMENT + "\n"))

    # `if inspect.isawaitable(x): await x` goes, and so does the `x = ` that only fed it.
    for function in ast.walk(cls):
        if not isinstance(function, FUNCTIONS):
            continue
        for body in statement_lists(function):
            for index, node in enumerate(body):
                name = awaited_name(node)
                if name is None:
                    continue
                last = node.end_lineno or node.lineno
                if not text.lines[node.lineno - 1].strip().startswith("if "):
                    raise GenerateError(f"line {node.lineno} of the class: an awaitable check sharing its line")
                rows.update(range(node.lineno, last + 1))
                edits.append((text.starts[node.lineno - 1], text.starts[last], ""))
                previous = body[index - 1] if index else None
                if (
                    isinstance(previous, ast.Assign)
                    and len(previous.targets) == 1
                    and isinstance(previous.targets[0], ast.Name)
                    and previous.targets[0].id == name
                    and loads(function, name) == loads(node, name)
                ):
                    edits.append((text.node_start(previous), text.node_start(previous.value), ""))
    return rows, edits


def token_edits(text: Text, cls: ast.ClassDef, skip_rows: Set[int], first_line: int) -> List[Edit]:
    """The unasync rewrite, token by token. f-strings are copied whole on every Python version."""
    docstrings: Dict[Tuple[int, int], bool] = {}  # start -> whether it is the class docstring
    for node in ast.walk(cls):
        if isinstance(node, (ast.ClassDef,) + FUNCTIONS):
            doc = docstring_node(node)
            if doc is not None:
                docstrings[(doc.lineno, text.char_col(doc.lineno, doc.col_offset))] = node is cls
    if True not in docstrings.values():
        raise GenerateError(f"{ASYNC_CLASS} has no docstring")
    # String annotations ("LeakRadarClient") get the NAMES renames of the code.
    annotation_strings: Set[Tuple[int, int]] = set()
    for node in ast.walk(cls):
        annotations: List[Optional[ast.expr]] = []
        if isinstance(node, FUNCTIONS):
            annotations += [arg.annotation for arg in arguments(node.args)] + [node.returns]
        elif isinstance(node, ast.AnnAssign):
            annotations.append(node.annotation)
        for annotation in annotations:
            for part in ast.walk(annotation) if annotation is not None else ():
                if isinstance(part, ast.Constant) and isinstance(part.value, str):
                    annotation_strings.add((part.lineno, text.char_col(part.lineno, part.col_offset)))

    tokens = list(tokenize.generate_tokens(io.StringIO(text.text).readline))
    edits: List[Edit] = []
    depth = 0
    for index, token in enumerate(tokens):
        kind = tokenize.tok_name.get(token.type, "")
        if kind in ("FSTRING_START", "TSTRING_START"):
            depth += 1
            continue
        if kind in ("FSTRING_END", "TSTRING_END"):
            depth -= 1
            continue
        if depth or token.start[0] in skip_rows:
            continue
        start = text.offset(*token.start)
        end = text.offset(*token.end)
        following = tokens[index + 1] if index + 1 < len(tokens) else None
        where = f"leakradar/client.py line {token.start[0] + first_line - 1}"
        if token.type == tokenize.NAME:
            if token.string == "async":
                if following is None or following.string not in ("def", "for", "with"):
                    raise GenerateError(f"{where}: unexpected `async`")
                edits.append((start, text.offset(*following.start), ""))
            elif token.string == "await":
                if following is None:
                    raise GenerateError(f"{where}: unexpected `await`")
                edits.append((start, text.offset(*following.start), ""))
            elif token.string in NAMES:
                edits.append((start, end, NAMES[token.string]))
            elif token.string in ("asyncio", "anyio"):
                attribute = tokens[index + 2].string if index + 2 < len(tokens) else ""
                module = ATTRIBUTES.get((token.string, attribute))
                if following is None or following.string != "." or module is None:
                    raise GenerateError(f"{where}: {token.string} is only rewritten in {sorted(ATTRIBUTES)}")
                edits.append((start, end, module))
        elif token.type == tokenize.STRING and token.start in docstrings:
            if docstrings[token.start]:
                edits.append((start, end, indent_block(CLASS_DOCSTRING, token.start[1])))
            else:
                edits.append((start, end, checked(reword(token.string), where)))
        elif token.type == tokenize.STRING and token.start in annotation_strings:
            edits.append((start, end, ASYNC_IDENTIFIERS.sub(lambda found: NAMES[found.group(0)], token.string)))
        elif token.type == tokenize.COMMENT:
            edits.append((start, end, checked(reword(token.string), where)))
    return edits


def check_sync_class(cls: ast.ClassDef) -> None:
    """The rewritten class has no async construct, and no string naming an async identifier."""
    docstrings = {id(doc) for doc in (docstring_node(node) for node in ast.walk(cls)) if doc is not None}
    for node in ast.walk(cls):
        line = getattr(node, "lineno", "?")
        if isinstance(node, (ast.AsyncFunctionDef, ast.Await, ast.AsyncFor, ast.AsyncWith)):
            raise GenerateError(f"line {line} of the rewritten class: {type(node).__name__} left (in an f-string?)")
        name = node.id if isinstance(node, ast.Name) else node.attr if isinstance(node, ast.Attribute) else None
        if name in FORBIDDEN:
            raise GenerateError(f"line {line} of the rewritten class: {name} left (in an f-string?)")
        if isinstance(node, ast.Constant) and isinstance(node.value, str) and id(node) not in docstrings:
            found = ASYNC_IDENTIFIERS.search(node.value)
            if found:
                raise GenerateError(f"line {line} of the rewritten class: a string names {found.group(0)}")


def parse_class(text: str, what: str) -> ast.ClassDef:
    try:
        tree = ast.parse(text)
    except SyntaxError as error:
        raise GenerateError(f"{what} does not parse: {error}") from None
    if len(tree.body) != 1 or not isinstance(tree.body[0], ast.ClassDef):
        raise GenerateError(f"{what} is not a single class")
    return tree.body[0]


def rewrite_class(source: Text, cls: ast.ClassDef) -> str:
    first = min([cls.lineno] + [decorator.lineno for decorator in cls.decorator_list])
    segment = Text("\n".join(source.lines[first - 1 : cls.end_lineno]) + "\n")
    local = parse_class(segment.text, f"class {ASYNC_CLASS}")
    rows, edits = statement_edits(local, segment)
    edits += token_edits(segment, local, rows, first)
    result = apply_edits(segment.text, edits)
    check_sync_class(parse_class(result, "the rewritten class"))
    return result


