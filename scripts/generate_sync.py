FUNCTIONS = (ast.FunctionDef, ast.AsyncFunctionDef)
COMPREHENSIONS = (ast.ListComp, ast.SetComp, ast.DictComp, ast.GeneratorExp)


class GenerateError(Exception):
    """client.py has something the generator cannot rewrite safely."""


class Binding:
    """What a name of client.py's namespace is bound to.

    kind: "import" (import module [as asname]), "from" (from module import name [as asname]),
    "relative" (from . import name [as asname]), "client" (anything else client.py binds: imported
    from .client), "guarded-import" / "guarded-from" (an import under `if TYPE_CHECKING:`).
    """

    def __init__(self, kind: str, module: str = "", name: str = "", asname: Optional[str] = None, group: int = 0):
        self.kind = kind
        self.module = module  # "os", "typing", "." for a relative import...
        self.name = name
        self.asname = asname
        self.group = group  # isort section of the import in client.py (blank-line separated)


