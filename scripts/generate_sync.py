def import_groups(tree: ast.Module, lines: List[str]) -> Dict[int, int]:
    """isort section of each top-level import of client.py: the blank lines between them tell."""
    groups: Dict[int, int] = {}
    group = 0
    previous: Optional[ast.stmt] = None
    for node in tree.body:
        if not isinstance(node, (ast.Import, ast.ImportFrom)):
            if previous is not None:
                group += 1
            previous = None
            continue
        if previous is not None:
            between = lines[(previous.end_lineno or previous.lineno) : node.lineno - 1]
            if any(not line.strip() for line in between):
                group += 1
        groups[id(node)] = group
        previous = node
    return groups


def is_type_checking(test: ast.AST) -> bool:
    if isinstance(test, ast.Name):
        return test.id == "TYPE_CHECKING"
    return isinstance(test, ast.Attribute) and test.attr == "TYPE_CHECKING"


def import_bindings(node: ast.stmt, group: int, guarded: bool) -> List[Tuple[str, Binding]]:
    found = []
    if isinstance(node, ast.Import):
        for alias in node.names:
            binding = Binding("guarded-import" if guarded else "import", alias.name, "", alias.asname, group)
            found.append((alias.asname or alias.name.split(".")[0], binding))
    elif isinstance(node, ast.ImportFrom):
        module = "." * node.level + (node.module or "")
        for alias in node.names:
            if guarded:
                binding = Binding("guarded-from", module, alias.name, alias.asname, group)
            elif not node.level:
                binding = Binding("from", module, alias.name, alias.asname, group)
            elif node.module is None:
                binding = Binding("relative", module, alias.name, alias.asname)
            else:
                binding = Binding("client")
            found.append((alias.asname or alias.name, binding))
    return found


def module_bindings(tree: ast.Module, lines: List[str]) -> Dict[str, Binding]:
    """What each name of client.py's namespace is bound to, the last binding winning."""
    groups = import_groups(tree, lines)
    bindings: Dict[str, Binding] = {}
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            bindings.update(import_bindings(node, groups[id(node)], False))
        elif isinstance(node, ast.If) and is_type_checking(node.test):
            for statement in node.body:
                if isinstance(statement, (ast.Import, ast.ImportFrom)):
                    bindings.update(import_bindings(statement, 0, True))
                else:
                    bindings.update((name, Binding("client")) for name in bound_names([statement]))
        else:
            bindings.update((name, Binding("client")) for name in bound_names([node]))
    return bindings


def natural(text: str) -> Tuple[str, ...]:
    """ruff's natural order: runs of digits compare by value."""
    return tuple(part.zfill(20) if part.isdigit() else part for part in re.split(r"(\d+)", text) if part)


def member_key(member: Member) -> Tuple[object, ...]:
    """ruff isort's order of the names of a from-import: CONSTANTS, then Classes, then the others."""
    name, asname = member
    kind = 0 if len(name) > 1 and name.isupper() else 1 if name[:1].isupper() else 2
    return (kind, natural(name.lower()), natural(name), asname or "")


def module_key(module: str) -> Tuple[object, ...]:
    """Relative imports furthest first, then by name."""
    bare = module.lstrip(".")
    return (len(bare) - len(module), natural(bare.lower()), natural(bare))


def from_import(module: str, members: List[Member], indent: str) -> str:
    names = [name + (f" as {asname}" if asname else "") for name, asname in sorted(members, key=member_key)]
    line = f"{indent}from {module} import {', '.join(names)}"
    if len(line) <= LINE_LENGTH:
        return line
    return "\n".join([f"{indent}from {module} import ("] + [f"{indent}    {name}," for name in names] + [f"{indent})"])


class Section:
    """The imports of one isort section."""

    def __init__(self) -> None:
        self.modules: Set[Member] = set()  # import module [as asname]
        self.members: Dict[str, Set[Member]] = {}  # from module import name [as asname]

    def add(self, binding: Binding) -> None:
        if binding.kind in ("import", "guarded-import"):
            self.modules.add((binding.module, binding.asname))
        else:
            self.members.setdefault(binding.module, set()).add((binding.name, binding.asname))

    def lines(self, indent: str = "") -> List[str]:
        """Plain imports first, then from-imports, each sorted by module (ruff's isort defaults)."""
        found = [
            f"{indent}import {module}" + (f" as {asname}" if asname else "")
            for module, asname in sorted(self.modules, key=lambda m: (module_key(m[0]), m[1] or ""))
        ]
        for module in sorted(self.members, key=module_key):
            plain = [member for member in self.members[module] if not member[1]]
            if plain:
                found.append(from_import(module, plain, indent))
            for member in sorted((m for m in self.members[module] if m[1]), key=member_key):
                found.append(from_import(module, [member], indent))
        return found


def import_block(reads: Set[str], bindings: Dict[str, Binding]) -> str:
    known = set(dir(builtins))
    renamed_from = {new: old for old, new in NAMES.items()}
    sections: Dict[int, Section] = {}
    local = Section()  # relative imports: always the last section
    guarded = Section()
    for name in sorted(reads):
        binding = bindings.get(name)
        if binding is None and name in known:
            continue
        if binding is None and name in ATTRIBUTES.values():
            binding = Binding("import", name)  # a module of the rewritten code (time)
        if binding is None and name in renamed_from:
            original = bindings.get(renamed_from[name])
            if original is not None and original.kind == "from":
                binding = Binding("from", original.module, name, None, original.group)
        if binding is None:
            raise GenerateError(f"the rewritten class reads `{name}`, which leakradar/client.py does not bind")
        if binding.kind == "client":
            local.add(Binding("from", ".client", name))
        elif binding.kind == "relative":
            local.add(binding)
        elif binding.kind.startswith("guarded"):
            guarded.add(binding)
        else:
            sections.setdefault(binding.group, Section()).add(binding)
    if guarded.modules or guarded.members:
        typing = next((b for b in bindings.values() if b.kind == "from" and b.module == "typing"), None)
        sections.setdefault(typing.group if typing else 0, Section()).add(Binding("from", "typing", "TYPE_CHECKING"))
    blocks = [sections[group].lines() for group in sorted(sections)] + [local.lines()]
    text = "\n\n".join("\n".join(block) for block in blocks if block)
    if guarded.modules or guarded.members:
        text += "\n\nif TYPE_CHECKING:\n" + "\n".join(guarded.lines("    "))
    return text


