"""
Generate leakradar/_sync_client.py, the synchronous client LeakRadar, from the asynchronous
LeakRadarClient of leakradar/client.py.

    python scripts/generate_sync.py              write leakradar/_sync_client.py
    python scripts/generate_sync.py --check      write nothing, exit with 1 when the file is out of date
    python scripts/generate_sync.py --out PATH   write PATH instead

The asynchronous code is the source: change LeakRadarClient, then run this script. The class is
rewritten token by token ("unasync", as httpx and httpcore do), so its comments and layout stay:

- async def -> def, await dropped, async with / async for -> with / for: a generator method
  annotated AsyncIterator[X] becomes a plain generator annotated Iterator[X];
- __aenter__ / __aexit__ / aclose -> __enter__ / __exit__ / close, for the client and for its
  httpx clients; httpx.AsyncClient / AsyncBaseTransport / AsyncHTTPTransport -> Client /
  BaseTransport / HTTPTransport; aiter_bytes / aread -> iter_bytes / read; asyncio.sleep and
  anyio.sleep -> time.sleep (NAMES, ATTRIBUTES);
- `if inspect.isawaitable(x): await x` is removed, and so is the `x = ` that only fed it: a
  synchronous client calls the callback, there is nothing to await;
- the class becomes LeakRadar, reads LEAKRADAR_API_KEY and LEAKRADAR_BASE_URL like
  AsyncLeakRadar (_READ_ENV = True), and gets its own docstring;
- docstrings and comments follow the WORDING rules, and string annotations ("LeakRadarClient")
  get the NAMES renames. No other string literal is rewritten, and an async construct or word the
  rules do not cover stops the script instead of being copied.

The imports are computed from the names the rewritten class reads: a module stays a plain import,
a name imported from another package is imported from it again, a sibling module imported with
`from . import` keeps that import, and everything else client.py binds (its helpers, constants,
type aliases, errors, __version__) is imported from .client.

The output depends on client.py alone, with the same bytes on every Python from 3.8 and LF line
endings: positions come from tokenize and ast (never ast.unparse), and f-strings, which Python
3.12 tokenizes into parts, are copied whole.
"""

